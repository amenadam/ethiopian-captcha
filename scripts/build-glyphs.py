#!/usr/bin/env python3
"""Generate src/render/glyphs.js (vector fidel + Ge'ez numerals) from a font.

Usage:  python3 scripts/build-glyphs.py NotoSansEthiopic-Bold.ttf [out.js]
Needs:  pip install fonttools
Use an OFL/permissively licensed font (Noto Sans Ethiopic, Abyssinica SIL).
The generated file embeds outlines from the font, so honour its licence.
"""
import json, pathlib, re, sys
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

root = pathlib.Path(__file__).resolve().parent.parent
if len(sys.argv) < 2:
    sys.exit(__doc__)
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / "src/render/glyphs.js"

letters = (root / "src/constants/amharicLetters.js").read_text(encoding="utf-8")
chars = sorted(set(re.findall(r"[\u1200-\u137F]", letters)) | {chr(c) for c in range(0x1369, 0x137B)})

font = TTFont(sys.argv[1])
cmap, gs = font.getBestCmap(), font.getGlyphSet()
k = 1000 / font["head"].unitsPerEm

class P(BasePen):
    def __init__(s, g): super().__init__(g); s.o = []
    def t(s, p): return f"{round(p[0]*k)} {round(-p[1]*k)}"
    def _moveTo(s, p): s.o.append("M" + s.t(p))
    def _lineTo(s, p): s.o.append("L" + s.t(p))
    def _qCurveToOne(s, a, b): s.o.append("Q" + s.t(a) + " " + s.t(b))
    def _curveToOne(s, a, b, c): s.o.append("C" + s.t(a) + " " + s.t(b) + " " + s.t(c))
    def _closePath(s): s.o.append("Z")
    def _endPath(s): s.o.append("Z")

glyphs, missing = {}, []
for ch in chars:
    name = cmap.get(ord(ch))
    if not name: missing.append(ch); continue
    p = P(gs); gs[name].draw(p)
    glyphs[ch] = {"w": round(gs[name].width * k), "d": "".join(p.o)}

if missing:
    sys.exit(f"Font lacks {len(missing)} needed glyphs: {''.join(missing)}")
fam = font["name"].getDebugName(1)
out.write_text(f"// Generated by scripts/build-glyphs.py from \"{fam}\". Do not edit.\n"
               f"export const GLYPHS = {json.dumps({'upm': 1000, 'glyphs': glyphs}, ensure_ascii=False, separators=(',', ':'))};\n",
               encoding="utf-8")
print(f"wrote {out} ({len(glyphs)} glyphs from {fam})")
